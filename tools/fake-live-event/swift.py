# swift.py <answers dir> <out.swift> : the answers as one raw-DEFLATE, base64 blob in a DEBUG-only Swift file.
import base64, json, os, sys, zlib

src, out = sys.argv[1], sys.argv[2]
files = {}
for base, _, names in os.walk(src):
    for name in names:
        path = os.path.join(base, name)
        files[os.path.relpath(path, src)] = open(path, encoding="utf-8").read()
packer = zlib.compressobj(9, zlib.DEFLATED, -15)
blob = packer.compress(json.dumps(files, ensure_ascii=False, sort_keys=True).encode()) + packer.flush()
text = base64.b64encode(blob).decode()
lines = [text[i:i + 120] for i in range(0, len(text), 120)]
with open(out, "w") as f:
    f.write("//\n//  FakeLiveEventData.swift\n//  Riftbound Companiokay\n//\n")
    f.write("//  Generated by tools/fake-live-event/build.sh, do not edit: the debug live event's PlayRiftbound answers\n")
    f.write("//  (fictional players and stores), JSON of file name → answer, raw DEFLATE, base64.\n//\n\n")
    f.write("#if DEBUG\nextension FakeLiveEvent {\n    nonisolated static let packed = \"\"\"\n")
    for line in lines:
        f.write("        " + line + "\n")
    f.write("        \"\"\"\n}\n#endif\n")
